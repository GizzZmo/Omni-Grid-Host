import type { SVGProps } from 'react';
type P = SVGProps<SVGSVGElement> & { size?: number | string };
function glyph(label: string) {
  return function Icon({ size = 16, ...props }: P) {
    return (
      <svg width={size} height={size} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" aria-hidden="true" {...props}>
        <circle cx="12" cy="12" r="9" opacity="0.35" />
        <text x="12" y="16" textAnchor="middle" fontSize="9" fill="currentColor" stroke="none">{label}</text>
      </svg>
    );
  };
}
